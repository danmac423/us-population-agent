  SNOWFLAKE.CORTEX.SEARCH_PREVIEW(
    'CENSUS_APP_DB.PUBLIC.CENSUS_TABLE_SEARCH',
    '{"query": "poverty by race",
      "columns": ["TABLE_ID", "DATA_TABLE_NAME", "TABLE_TITLE", "SEARCH_TEXT"],
      "limit": 10}'
  )
):results AS results;

