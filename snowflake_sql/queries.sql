-- 3) Column name and geo data
SELECT 
    CASE 
        WHEN v.STATE_ABBR = 'TX' THEN 'Teksas' 
        ELSE 'Reszta USA' 
    END AS OBSZAR,
    SUM(d."B29003e2") AS LACZNIE_PONIZEJ_PROGU_UBOSTWA,
    SUM(d."B29003e1") AS POPULACJA_CALKOWITA,
    ROUND((SUM(d."B29003e2") / NULLIF(SUM(d."B29003e1"), 0)) * 100, 2) AS WSKAZNIK_UBOSTWA_PROCENT
FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B29" d
JOIN CENSUS_APP_DB.PUBLIC.V_GEOGRAPHY v 
    USING (CENSUS_BLOCK_GROUP)
GROUP BY 
    CASE 
        WHEN v.STATE_ABBR = 'TX' THEN 'Teksas' 
        ELSE 'Reszta USA' 
    END;


SELECT v.STATE_ABBR,
  SUM(d."B01001e3" + d."B01001e4" + d."B01001e5" + d."B01001e6" + d."B01001e27" + d."B01001e28" + d."B01001e29" + d."B01001e30") AS POPULATION_UNDER_18,
  COUNT(*) AS N_CBG
FROM US_OPEN_CENSUS_DATA_NEIGHBORHOOD_INSIGHTS_FREE_DATASET.PUBLIC."2020_CBG_B01" d
JOIN V_GEOGRAPHY v USING (CENSUS_BLOCK_GROUP)
WHERE v.STATE_ABBR = 'TX'
GROUP BY v.STATE_ABBR;

